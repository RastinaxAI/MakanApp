public sealed class GlobalExceptionHandler(
    ILogger<GlobalExceptionHandler> logger,
    IProblemDetailsService problemDetailsService) : IExceptionHandler
{
    public async ValueTask<bool> TryHandleAsync(
        HttpContext httpContext,
        Exception exception,
        CancellationToken cancellationToken)
    {
        var problemDetails = exception switch
        {
            AssessmentException assessmentException => CreateKnownProblem(
                assessmentException.Code,
                assessmentException.Message),
            AiServiceException aiException => CreateKnownProblem(
                aiException.Code,
                aiException.Message),
            CommerceException commerceException => CreateKnownProblem(
                commerceException.Code,
                commerceException.Message),
            AcademicException academicException => CreateKnownProblem(
                academicException.Code,
                academicException.Message),
            IdentityException identityException => CreateKnownProblem(
                identityException.Code,
                identityException.Message),
            MessagingException messagingException => CreateKnownProblem(
                messagingException.Code,
                messagingException.Message),
            NotificationException notificationException => CreateKnownProblem(
                notificationException.Code,
                notificationException.Message),
            NotificationPreferenceException preferenceException => CreateKnownProblem(
                preferenceException.Code,
                preferenceException.Message),
            OrganizationException organizationException => CreateKnownProblem(
                organizationException.Code,
                organizationException.Message),
            PlatformException platformException => CreateKnownProblem(
                platformException.Code,
                platformException.Message),
            GuardianException guardianException => CreateKnownProblem(
                guardianException.Code,
                guardianException.Message),
            StorageException storageException => CreateKnownProblem(
                storageException.Code,
                storageException.Message),
            DetailedReportException detailedReportException => CreateKnownProblem(
                detailedReportException.Code,
                detailedReportException.Message),
            ReportExportException reportExportException => CreateKnownProblem(
                reportExportException.Code,
                reportExportException.Message),
            _ => CreateUnexpectedProblem(exception, httpContext.TraceIdentifier)
        };

        httpContext.Response.StatusCode = problemDetails.Status
            ?? StatusCodes.Status500InternalServerError;

        return await problemDetailsService.TryWriteAsync(new ProblemDetailsContext
        {
            HttpContext = httpContext,
            ProblemDetails = problemDetails
        });
    }

